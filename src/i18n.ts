// Polish and English. The language follows the phone unless the player picks one in settings.

export type Lang = 'pl' | 'en';
export let lang: Lang = 'pl';

export function setLang(pref: 'auto' | Lang): void {
  if (pref !== 'auto') lang = pref;
  else lang = (navigator.language || 'pl').toLowerCase().startsWith('pl') ? 'pl' : 'en';
  document.documentElement.lang = lang;
}

/** Text in both languages, picked at call time. */
export interface Txt { pl: string; en: string }
export const L = (pl: string, en: string): Txt => ({ pl, en });
export const tx = (t: Txt | string): string => (typeof t === 'string' ? t : t[lang]);

export function fmt(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

export function fmtTime(sec: number): string {
  sec = Math.max(0, Math.floor(sec));
  const h = Math.floor(sec / 3600);
  const m = Math.floor((sec % 3600) / 60);
  const s = sec % 60;
  const mm = h ? String(m).padStart(2, '0') : String(m);
  return (h ? `${h}:` : '') + `${mm}:${String(s).padStart(2, '0')}`;
}

